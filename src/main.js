/**
 * 1. Live Studio Clock (Portugal GMT+0)
 */
function initLiveClock() {
  const headerTimeEl = document.getElementById('header-time');
  const footerTimeEl = document.getElementById('footer-time');
  const heroTimeEl = document.getElementById('hero-clock-time');

  function updateClock() {
    const now = new Date();
    const options = {
      timeZone: 'Europe/Lisbon',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false
    };
    const timeParts = new Intl.DateTimeFormat('en-GB', {
      ...options,
      second: '2-digit'
    }).formatToParts(now);

    const hours = parseInt(timeParts.find(p => p.type === 'hour')?.value || '16', 10);
    const minutes = parseInt(timeParts.find(p => p.type === 'minute')?.value || '49', 10);
    const timeStr = `${hours < 10 ? '0' : ''}${hours}:${minutes < 10 ? '0' : ''}${minutes}`;

    if (headerTimeEl) {
      headerTimeEl.textContent = timeStr;
    }
    if (footerTimeEl) {
      footerTimeEl.textContent = `${timeStr} PORTUGAL (GMT+0)`;
    }
    if (heroTimeEl) {
      heroTimeEl.textContent = timeStr;
    }
  }

  updateClock();
  setInterval(updateClock, 1000);
}

/**
 * 2. Areas of Expertise Carousel
 */
function initExpertiseCarousel() {
  const viewport = document.getElementById('expertise-viewport');
  const prevBtn = document.getElementById('carousel-prev');
  const nextBtn = document.getElementById('carousel-next');
  const cards = document.querySelectorAll('.expertise-card');

  if (!viewport || !cards.length) return;

  const totalCards = cards.length;
  let currentIndex = 0;

  function getMaxScrollLeft() {
    return Math.max(0, viewport.scrollWidth - viewport.clientWidth);
  }

  function updateActiveState(index) {
    const maxScroll = getMaxScrollLeft();
    const isAtEnd = maxScroll > 0 && viewport.scrollLeft >= maxScroll - 15;

    if (isAtEnd) {
      currentIndex = totalCards - 1;
    } else {
      currentIndex = Math.max(0, Math.min(index, totalCards - 1));
    }
  }

  function scrollToIndex(index) {
    const maxScroll = getMaxScrollLeft();
    if (index >= totalCards - 1) {
      viewport.scrollTo({ left: maxScroll, behavior: 'smooth' });
      updateActiveState(totalCards - 1);
      return;
    }
    if (index <= 0) {
      viewport.scrollTo({ left: 0, behavior: 'smooth' });
      updateActiveState(0);
      return;
    }

    if (cards[index]) {
      const targetLeft = Math.min(cards[index].offsetLeft - viewport.offsetLeft, maxScroll);
      viewport.scrollTo({
        left: targetLeft,
        behavior: 'smooth'
      });
      updateActiveState(index);
    }
  }

  if (prevBtn) {
    prevBtn.addEventListener('click', () => {
      const maxScroll = getMaxScrollLeft();
      if (viewport.scrollLeft <= 15) {
        viewport.scrollTo({ left: maxScroll, behavior: 'smooth' });
      } else {
        scrollToIndex(Math.max(0, currentIndex - 1));
      }
    });
  }

  if (nextBtn) {
    nextBtn.addEventListener('click', () => {
      const maxScroll = getMaxScrollLeft();
      if (viewport.scrollLeft >= maxScroll - 15) {
        scrollToIndex(0);
      } else {
        scrollToIndex(currentIndex + 1);
      }
    });
  }

  let scrollTimeout;
  viewport.addEventListener('scroll', () => {
    clearTimeout(scrollTimeout);
    scrollTimeout = setTimeout(() => {
      const scrollLeft = viewport.scrollLeft;
      const maxScroll = getMaxScrollLeft();

      if (maxScroll > 0 && scrollLeft >= maxScroll - 15) {
        updateActiveState(totalCards - 1);
        return;
      }

      let closestIdx = 0;
      let minDiff = Infinity;
      cards.forEach((card, idx) => {
        const diff = Math.abs((card.offsetLeft - viewport.offsetLeft) - scrollLeft);
        if (diff < minDiff) {
          minDiff = diff;
          closestIdx = idx;
        }
      });
      updateActiveState(closestIdx);
    }, 50);
  }, { passive: true });
}

/**
 * 3. Inquiry Form Handler
 */
function initInquiryForm() {
  const form = document.getElementById('inquiry-form');
  const feedback = document.getElementById('form-feedback');

  if (!form) return;

  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const btn = form.querySelector('.submit-btn');
    if (btn) btn.disabled = true;

    const dict = translations[currentLanguage] || translations['en'];

    if (feedback) {
      feedback.style.color = '#e5a83b';
      feedback.textContent = dict['form_sending'] || 'TRANSMITTING PARAMETERS TO BRUTO...';
    }

    setTimeout(() => {
      if (feedback) {
        feedback.style.color = '#34d399';
        feedback.textContent = dict['form_success'] || '✓ TRANSMISSION CONFIRMED. A PRINCIPAL WILL INITIATE CONTACT WITHIN 24 HOURS.';
      }
      form.reset();
      if (btn) btn.disabled = false;
    }, 800);
  });
}

/**
 * 4. Hero Video Engine & Interactive Controls
 */
function initHeroVideo() {
  const video = document.getElementById('hero-bg-video');
  const badge = document.getElementById('video-status-badge');
  const heroStage = document.getElementById('hero-stage-container');

  if (!video) return;

  video.muted = true;

  function markVideoActive() {
    video.classList.add('is-playing');
    if (badge) badge.classList.add('is-hidden');
  }

  video.addEventListener('playing', markVideoActive);
  video.addEventListener('loadeddata', () => {
    if (video.readyState >= 2) {
      markVideoActive();
    }
  });

  if (!video.paused && video.readyState >= 2) {
    markVideoActive();
  }

  if (heroStage) {
    ['dragenter', 'dragover'].forEach(name => {
      heroStage.addEventListener(name, (e) => {
        e.preventDefault();
        e.stopPropagation();
        heroStage.style.borderColor = '#e5a83b';
        heroStage.style.boxShadow = '0 0 50px rgba(229, 168, 59, 0.4)';
      });
    });

    ['dragleave', 'drop'].forEach(name => {
      heroStage.addEventListener(name, (e) => {
        e.preventDefault();
        e.stopPropagation();
        heroStage.style.borderColor = 'rgba(255, 255, 255, 0.08)';
        heroStage.style.boxShadow = '';
      });
    });

    heroStage.addEventListener('drop', (e) => {
      const files = e.dataTransfer.files;
      if (files && files.length > 0) {
        const file = files[0];
        if (file.type.startsWith('video/') || /\.(mp4|webm|mov|mkv)$/i.test(file.name)) {
          const videoUrl = URL.createObjectURL(file);
          video.src = videoUrl;
          video.play().then(markVideoActive).catch(err => console.log('Autoplay deferred:', err));
        }
      }
    });
  }
}

/**
 * 5. Floating Bottom Navigation Pill (Mobile / Tablet)
 */
function initMobileNavPill() {
  const pill = document.getElementById('mobile-nav-pill');
  if (!pill) return;

  const links = pill.querySelectorAll('.pill-link');
  const sections = ['manifesto', 'capabilities', 'expertise', 'about'];
  const sectionEls = sections.map(id => document.getElementById(id)).filter(Boolean);
  const heroEl = document.getElementById('hero');

  function updatePillState() {
    const scrollY = window.scrollY;
    const heroHeight = heroEl ? heroEl.offsetHeight : 500;

    if (scrollY > heroHeight * 0.35) {
      pill.classList.add('is-visible');
    } else {
      pill.classList.remove('is-visible');
    }

    let activeId = null;
    const scrollPos = scrollY + window.innerHeight * 0.35;

    for (let i = sectionEls.length - 1; i >= 0; i--) {
      const el = sectionEls[i];
      if (el && el.offsetTop <= scrollPos) {
        activeId = el.id;
        break;
      }
    }

    links.forEach(link => {
      const section = link.getAttribute('data-section');
      if (section === activeId) {
        link.classList.add('active');
      } else {
        link.classList.remove('active');
      }
    });
  }

  links.forEach(link => {
    link.addEventListener('click', (e) => {
      e.preventDefault();
      const targetId = link.getAttribute('href')?.replace('#', '');
      const targetEl = document.getElementById(targetId);
      if (targetEl) {
        const offset = 80;
        const top = targetEl.getBoundingClientRect().top + window.pageYOffset - offset;
        window.scrollTo({ top, behavior: 'smooth' });
      }
    });
  });

  window.addEventListener('scroll', updatePillState, { passive: true });
  updatePillState();
}

/**
 * 6. Capabilities Mobile Tap-to-Peel Stacked Deck
 */
function initCapabilitiesStack() {
  const cards = document.querySelectorAll('.services-grid .service-item');
  if (!cards.length) return;

  cards[0].classList.add('is-peeled');

  cards.forEach((card, index) => {
    card.setAttribute('data-card-index', index);
    card.addEventListener('click', () => {
      if (window.innerWidth > 767) return;
      cards.forEach(c => c.classList.remove('is-peeled'));
      card.classList.add('is-peeled');
    });
  });
}

