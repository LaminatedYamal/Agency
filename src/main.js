let currentLanguage = 'en';

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'pt') lang = 'en';
  currentLanguage = lang;
  localStorage.setItem('bruto_lang', lang);
  document.documentElement.lang = lang;

  const dict = translations[lang];
  if (!dict) return;

  // 1. Text & HTML replacement via data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (dict[key].includes('<')) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // 2. Placeholders via data-i18n-ph
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // 3. Update Header toggle buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // 4. Update dynamic mobile pill labels
  const pillLinks = document.querySelectorAll('.pill-link');
  pillLinks.forEach(link => {
    const sec = link.getAttribute('data-section');
    if (sec === 'manifesto') link.setAttribute('data-label', dict['pill_process'] || 'PROCESS');
    if (sec === 'capabilities') link.setAttribute('data-label', dict['pill_capabilities'] || 'CAPABILITIES');
    if (sec === 'expertise') link.setAttribute('data-label', dict['pill_expertise'] || 'EXPERTISE');
    if (sec === 'about') link.setAttribute('data-label', dict['pill_about'] || 'ABOUT');
  });
}

function initI18n() {
  const saved = localStorage.getItem('bruto_lang');
  let initial = 'en';
  if (saved === 'en' || saved === 'pt') {
    initial = saved;
  } else {
    const browserLang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (browserLang.startsWith('pt')) {
      initial = 'pt';
    }
  }

  setLanguage(initial);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = btn.getAttribute('data-lang');
      setLanguage(lang);
    });
  });
}

